<#
.SYNOPSIS
    R19: runs Milan Pro's playback benchmarks and writes docs/PERFORMANCE.md from what they measure.
.DESCRIPTION
    Generates the synthetic bench media with ffmpeg lavfi (4 x 12 s 1080p29.97 H.264, GOP 250, cached in -Media),
    then runs each ignored benchmark alone in a release build (`cargo test --release -- --ignored --test-threads=1`)
    and fills the tables from the `BENCH` lines they print. The R20 tests make their own media and proxies in -Media
    too. Needs ffmpeg on PATH. Takes about 5 minutes; keep the machine otherwise idle while it runs.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\bench.ps1
#>
param(
    [string]$Media = (Join-Path $env:TEMP 'milan-bench'),
    [string]$Out = (Join-Path (Split-Path $PSScriptRoot -Parent) 'docs\PERFORMANCE.md')
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

# Synthetic media: what `bench_project` in src/engine/worker.rs reads (it makes any file missing the same way).
New-Item -ItemType Directory -Force $Media | Out-Null
for ($i = 0; $i -lt 4; $i++) {
    $f = Join-Path $Media "bench$i-12.mp4"
    if (-not (Test-Path $f)) {
        & ffmpeg -nostdin -v error -y -f lavfi -i "testsrc2=size=1920x1080:rate=30000/1001:duration=12,hue=h=$($i * 90)" -c:v libx264 -preset veryfast -g 250 -pix_fmt yuv420p $f
        if ($LASTEXITCODE) { throw "ffmpeg could not make $f" }
    }
}
$env:MILAN_BENCH_DIR = $Media

$tests = @(
    'engine::worker::tests::bench_playback',
    'engine::worker::tests::bench_scrub',
    'engine::worker::tests::bench_playback_with_scopes',
    'engine::worker::tests::bench_playback_multicam_grid',
    'engine::tests::bench_adaptive_quality',
    'engine::worker::tests::seeks_are_frame_exact_on_long_gop',
    'engine::worker::tests::scrub_drag_follows_the_cursor',
    'engine::worker::tests::reverse_playback_shows_every_frame',
    'engine::ofx::tests::bench_ofx_roundtrip_1080p',
    'engine::aplug::tests::bench_vst3_block_overhead',
    'engine::gpu::tests::bench_compose',
    'engine::worker::tests::bench_ram_preview',
    'engine::worker::tests::bench_disk_cache',
    'engine::hw::tests::hw_capability_table'
)
# Each BENCH line: "BENCH <name> key=value ...".
$bench = @()
Push-Location $root
try {
    foreach ($t in $tests) {
        Write-Host "Running $t"
        $lines = & cargo test --release -q -- --ignored --nocapture --test-threads=1 --exact $t | ForEach-Object { "$_" }
        if ($LASTEXITCODE) { $lines | Write-Host; throw "$t failed" }
        foreach ($l in $lines | Where-Object { $_ -like 'BENCH *' }) {
            $parts = $l.Split(' ')
            $kv = @{ name = $parts[1] }
            foreach ($p in $parts[2..($parts.Length - 1)]) { $k, $v = $p.Split('=', 2); $kv[$k] = $v }
            $bench += [pscustomobject]$kv
        }
    }
    $commit = (& git rev-parse --short HEAD).Trim()
    $dirty = if (& git status --porcelain -- src) { ' plus uncommitted changes in src' } else { '' }
    $rustc = (& rustc --version).Trim()
} finally {
    Pop-Location
}

# The machine.
$cpu = Get-CimInstance Win32_Processor | Select-Object -First 1
$os = Get-CimInstance Win32_OperatingSystem
$ram = [math]::Round((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB, 1)
$gpus = (Get-CimInstance Win32_VideoController | ForEach-Object { $_.Name }) -join ', '
$ffmpeg = ((& ffmpeg -hide_banner -version | Select-Object -First 1) -replace '^ffmpeg version (\S+).*', '$1')
$power = try { ((& powercfg /getactivescheme) -replace '.*\((.*)\).*', '$1').Trim() } catch { 'unknown' }

function Rows($name) { $bench | Where-Object { $_.name -eq $name } }
function Gate($ok) { if ($ok) { 'pass' } else { 'FAIL' } }

$md = New-Object System.Text.StringBuilder
function L($s = '') { [void]$md.AppendLine($s) }
L '# Milan Pro performance'
L ''
L "Generated by ``tools/bench.ps1`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm') at commit $commit$dirty. Do not edit by hand: run the script again (about 5 minutes, machine otherwise idle) and commit the result."
L 'Every number below was measured by that run; nothing is estimated.'
L ''
L '## Machine'
L ''
L '| | |'
L '|---|---|'
L "| CPU | $($cpu.Name.Trim()), $($cpu.NumberOfCores) cores / $($cpu.NumberOfLogicalProcessors) threads |"
L "| RAM | $ram GB |"
$adapter = Rows 'adapter' | Select-Object -First 1
$gpuNote = if ($adapter) { "compositing on $($adapter.adapter -replace '_', ' ') through Vulkan (R21a)" } else { 'no Vulkan adapter: compositing on the CPU' }
L "| GPU | $gpus ($gpuNote) |"
L "| OS | $($os.Caption) $($os.Version) |"
L "| Power plan | $power |"
L "| Build | ``cargo test --release``, $rustc |"
L "| FFmpeg | $ffmpeg (decoders run out of process, ``-threads 2`` each) |"
L ''
L '## Method'
L ''
L '- **Media.** Four 12 s clips made with ffmpeg lavfi: `testsrc2` 1920x1080 at 29.97 fps, each hue-shifted, H.264 (libx264 `veryfast`, GOP 250, yuv420p). One track per clip at Level 50 %, so every layer is decoded and blended; no proxies.'
L '- **Playback** (`bench_playback`, `bench_playback_with_scopes`, `bench_playback_multicam_grid` in `src/engine/worker.rs`). The video worker plays the project at the default preview, Preview (Auto) at 960x540, against a 29.97 fps clock that starts with the first frame, as the audio clock drives it in the app. Like the Video Preview, the test takes a frame once its number is due, polling every 1 ms, for 240 frames.'
L '  - *fps*: frames shown per second of wall time.'
L '  - *Dropped*: frames never shown (the worker skipped them to catch up, or a newer one was already due), as a share of the frames due.'
L '  - *Late layer frames*: layer pictures that missed their 25 ms deadline (the layer held its last picture) or that a decoder read past.'
L '  - *Play start*: from Play to the first frame, decoders cold (each run starts a new worker).'
L '  - *Video behind audio*: for each frame shown, the clock time when it went on screen less its own time: the preview pipeline''s A/V offset, before the display and the audio device latency (which the player compensates, R9).'
L '  - *Unpaced*: frames composed per second when nothing paces the worker (each frame waits for its decoders).'
L '- **Scopes**: the same playback while a thread analyses a 960x540 frame with all four Video Scopes 10 times a second (Update Scopes while Playing).'
L '- **Multicam grid**: the four clips made one multicamera track; the Video Preview shows the 2x2 take grid.'
L '- **Scrub** (`bench_scrub`): 40 paused frame requests on one layer at 960x540, as dragging the cursor makes them: 30 forward steps, then jumps (300, 100, 250, 20) and steps after them. A jump in GOP-250 media respawns its decoder. *Steps back*: 60 single frames backwards from frame 300 (dragging left, J at -1x), read from chunks decoded forward (R20). Each also on the clip''s video proxy (`proxy::args`: 1280 wide, a keyframe every 15 frames), which Preview reads.'
L '- **Seeks** (`seeks_are_frame_exact_on_long_gop`): a 20 s 1920x1080 30 fps H.264 clip, one keyframe every 250 frames, with its frame number burnt in as 10 black or white blocks; 200 random paused frames at 960x540 (Good on the source, Preview on its proxy), each checked to be exactly the frame asked for.'
L '- **Scrub drag** (`scrub_drag_follows_the_cursor`): the same clip, the cursor dragged at 2x for 3 s backwards and forwards through `VideoEngine` as the Video Preview drives it (60 Hz); at every UI frame, how far the frame on screen (read from its burnt-in number) is from the cursor.'
L '- **Reverse playback** (`reverse_playback_shows_every_frame`): the same clip as a reversed event, played at 1x for 10 s against a 30 fps clock as above; a frame counts when the one on screen is exactly the source frame due.'
L '- **Adjust Size and Quality for Optimal Playback** (`bench_adaptive_quality` in `src/engine/mod.rs`): the four layers at Best (Full), 1920x1080, looped for 60 s through the Video Preview itself (`decode::Preview`, a 60 Hz UI loop against the wall clock), with the option off and then on.'
L '- **GPU compositor** (`bench_compose` in `src/engine/gpu/mod.rs`, R21a-c): four decoded layers composed into one frame, on the CPU and on the GPU, median of 30 after a warm-up: four full 1920x1080 frames at Level 50 % (the project of the playback benches), four 1920x1080 picture-in-pictures at 45 % turned 15 degrees, and four full 3840x2160 frames (a 4K project at Best (Full)). *As the preview gets it*: the frame stays on the GPU (R21c); *read back*: its pixels copied to the CPU too, as a render needs them. The GPU times include uploading the decoded pictures (32 MB a frame at 1080p full, 133 MB at 4K).
- **OFX host round trip** (`bench_ofx_roundtrip_1080p` in `src/engine/ofx/tests.rs`, R33b): one 1920x1080 frame through the test bundle''s invert plug-in in `milan-plugin-host.exe` (the frame to shared memory as 32-bit float or 8-bit RGBA, the render action, the result back and converted), 20 frames after a warm-up, against the built-in invert on all cores. The overhead is the float round trip less the built-in time: what hosting costs on top of a plug-in''s own work.
- **Dynamic RAM Preview** (`bench_ram_preview` in `src/engine/worker.rs`, R23): Build Dynamic RAM Preview over the first 8 s (240 frames) of the four-layer project at Preview (960x540), then that range played against the 29.97 fps clock as above with every decoder closed, so each frame comes from the RAM preview.
- **Disk frame cache** (`bench_disk_cache`, R23): 30 paused seeks (as dragging the cursor makes them) into a 10 s 1920x1080 HEVC clip (libx265 `ultrafast`, GOP 250) at 960x540 Good, with the cache off, with it filling, and again with every frame cached; the cache holds raw RGBA frames under `%LOCALAPPDATA%\MilanPro\framecache` (off by default; Preferences > Video).
- **Hardware acceleration** (`hw_capability_table` in `src/engine/hw.rs`, R22): the capability probe Milan Pro runs at startup: each FFmpeg hardware decoder path (d3d11va, cuda, qsv) on a 5 s 1080p H.264, HEVC and AV1 clip against the 2-thread software decoder (the better of two runs each, ffmpeg start-up included; the hardware path downloads its frames to system memory as playback needs them), and each hardware encoder on the same 150 generated frames. Automatic decode acceleration uses a path only where it measured faster than software.
- **VST3 block** (`bench_vst3_block_overhead` in `src/engine/aplug/tests.rs`, R34a): one 1024-frame stereo block through the test module''s gain effect in `milan-plugin-host.exe` (the block to shared memory, the process request, the result back), 500 blocks after a warm-up, against a built-in audio plug-in at a plain gain (the compressor at 1:1 with output gain) in the same chain. The overhead is the difference: what hosting an audio plug-in costs per block.'
L ''

L '## Playback, Preview (960x540)'
L ''
L '| Layers | fps | Dropped | Late layer frames | Play start | Video behind audio p50 / p95 / max | Unpaced |'
L '|---|---|---|---|---|---|---|'
foreach ($r in Rows 'playback') { L "| $($r.layers) | $($r.fps) | $($r.drop_pct) % | $($r.late_layer_frames) | $($r.start_ms) ms | $($r.av_p50_ms) / $($r.av_p95_ms) / $($r.av_max_ms) ms | $($r.unpaced_fps) fps |" }
L ''
L '### With the Video Scopes updating while playing'
L ''
L '| Layers | fps | Dropped | Late layer frames | Play start | Video behind audio p50 / p95 |'
L '|---|---|---|---|---|---|'
foreach ($r in Rows 'scopes') { L "| $($r.layers) | $($r.fps) | $($r.drop_pct) % | $($r.late_layer_frames) | $($r.start_ms) ms | $($r.av_p50_ms) / $($r.av_p95_ms) ms |" }
L ''
L '### Multicamera take grid'
L ''
L '| Takes | fps | Dropped | Late layer frames | Play start | Video behind audio p50 / p95 |'
L '|---|---|---|---|---|---|'
foreach ($r in Rows 'multicam') { L "| $($r.takes) | $($r.fps) | $($r.drop_pct) % | $($r.late_layer_frames) | $($r.start_ms) ms | $($r.av_p50_ms) / $($r.av_p95_ms) ms |" }
L ''
L '## Scrub (one layer, 960x540)'
L ''
$s = Rows 'scrub' | Select-Object -First 1
$sp = Rows 'scrub_proxy' | Select-Object -First 1
L '| Media | Requests | p50 | p95 | max |'
L '|---|---|---|---|---|'
foreach ($r in @(@('Original (GOP 250)', 'Steps and jumps', 'scrub'), @('Original (GOP 250)', 'Steps back', 'scrub_back'), @('Proxy', 'Steps and jumps', 'scrub_proxy'), @('Proxy', 'Steps back', 'scrub_back_proxy'))) {
    $x = Rows $r[2] | Select-Object -First 1
    L "| $($r[0]) | $($r[1]) | $($x.p50_ms) ms | $($x.p95_ms) ms | $($x.max_ms) ms |"
}
L ''
L '### Random seeks (200, each checked to be the exact frame)'
L ''
L '| Media | p50 | p95 | max |'
L '|---|---|---|---|'
foreach ($r in Rows 'seek') { L "| $(if ($r.proxy -eq 'true') { 'Proxy, Preview' } else { 'Original (GOP 250), Good' }) | $($r.p50_ms) ms | $($r.p95_ms) ms | $($r.max_ms) ms |" }
L ''
L '### Dragging the cursor at 2x: how far the picture trails it'
L ''
L '| Media | Direction | p95 | max |'
L '|---|---|---|---|'
foreach ($r in Rows 'drag') { L "| $(if ($r.proxy -eq 'true') { 'Proxy' } else { 'Original (GOP 250)' }) | $(if ($r.dir -eq 'back') { 'Backwards' } else { 'Forwards' }) | $($r.lag_p95_s) s | $($r.lag_max_s) s |" }
L ''
L '## Reverse playback (reversed event, 1x, 960x540, original GOP-250 media)'
