<#
.SYNOPSIS
    R19: runs Milan Pro's playback benchmarks and writes docs/PERFORMANCE.md from what they measure.
.DESCRIPTION
    Generates the synthetic bench media with ffmpeg lavfi (4 x 12 s 1080p29.97 H.264, GOP 250, cached in -Media),
    then runs each ignored benchmark alone in a release build (`cargo test --release -- --ignored --test-threads=1`)
    and fills the tables from the `BENCH` lines they print. Needs ffmpeg on PATH. Takes about 4 minutes; keep the
    machine otherwise idle while it runs.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\bench.ps1
#>
param(
    [string]$Media = (Join-Path $env:TEMP 'milan-bench'),
    [string]$Out = (Join-Path (Split-Path $PSScriptRoot -Parent) 'docs\PERFORMANCE.md')
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

# Synthetic media: what `bench_project` in src/engine/worker.rs reads (it makes any file missing the same way).
New-Item -ItemType Directory -Force $Media | Out-Null
for ($i = 0; $i -lt 4; $i++) {
    $f = Join-Path $Media "bench$i-12.mp4"
    if (-not (Test-Path $f)) {
        & ffmpeg -nostdin -v error -y -f lavfi -i "testsrc2=size=1920x1080:rate=30000/1001:duration=12,hue=h=$($i * 90)" -c:v libx264 -preset veryfast -g 250 -pix_fmt yuv420p $f
        if ($LASTEXITCODE) { throw "ffmpeg could not make $f" }
    }
}
$env:MILAN_BENCH_DIR = $Media

$tests = @(
    'engine::worker::tests::bench_playback',
    'engine::worker::tests::bench_scrub',
    'engine::worker::tests::bench_playback_with_scopes',
    'engine::worker::tests::bench_playback_multicam_grid',
    'engine::tests::bench_adaptive_quality'
)
# Each BENCH line: "BENCH <name> key=value ...".
$bench = @()
Push-Location $root
try {
    foreach ($t in $tests) {
        Write-Host "Running $t"
        $lines = & cargo test --release -q -- --ignored --nocapture --test-threads=1 --exact $t | ForEach-Object { "$_" }
        if ($LASTEXITCODE) { $lines | Write-Host; throw "$t failed" }
        foreach ($l in $lines | Where-Object { $_ -like 'BENCH *' }) {
            $parts = $l.Split(' ')
            $kv = @{ name = $parts[1] }
            foreach ($p in $parts[2..($parts.Length - 1)]) { $k, $v = $p.Split('=', 2); $kv[$k] = $v }
            $bench += [pscustomobject]$kv
        }
    }
    $commit = (& git rev-parse --short HEAD).Trim()
    $dirty = if (& git status --porcelain -- src) { ' plus uncommitted changes in src' } else { '' }
    $rustc = (& rustc --version).Trim()
} finally {
    Pop-Location
}

# The machine.
$cpu = Get-CimInstance Win32_Processor | Select-Object -First 1
$os = Get-CimInstance Win32_OperatingSystem
$ram = [math]::Round((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB, 1)
$gpus = (Get-CimInstance Win32_VideoController | ForEach-Object { $_.Name }) -join ', '
$ffmpeg = ((& ffmpeg -hide_banner -version | Select-Object -First 1) -replace '^ffmpeg version (\S+).*', '$1')
$power = try { ((& powercfg /getactivescheme) -replace '.*\((.*)\).*', '$1').Trim() } catch { 'unknown' }

function Rows($name) { $bench | Where-Object { $_.name -eq $name } }
function Gate($ok) { if ($ok) { 'pass' } else { 'FAIL' } }

$md = New-Object System.Text.StringBuilder
function L($s = '') { [void]$md.AppendLine($s) }
L '# Milan Pro performance'
L ''
L "Generated by ``tools/bench.ps1`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm') at commit $commit$dirty. Do not edit by hand: run the script again (about 4 minutes, machine otherwise idle) and commit the result."
L 'Every number below was measured by that run; nothing is estimated.'
L ''
L '## Machine'
L ''
L '| | |'
L '|---|---|'
L "| CPU | $($cpu.Name.Trim()), $($cpu.NumberOfCores) cores / $($cpu.NumberOfLogicalProcessors) threads |"
L "| RAM | $ram GB |"
L "| GPU | $gpus (unused: compositing is on the CPU until R21a) |"
L "| OS | $($os.Caption) $($os.Version) |"
L "| Power plan | $power |"
L "| Build | ``cargo test --release``, $rustc |"
L "| FFmpeg | $ffmpeg (decoders run out of process, ``-threads 2`` each) |"
L ''
L '## Method'
L ''
L '- **Media.** Four 12 s clips made with ffmpeg lavfi: `testsrc2` 1920x1080 at 29.97 fps, each hue-shifted, H.264 (libx264 `veryfast`, GOP 250, yuv420p). One track per clip at Level 50 %, so every layer is decoded and blended; no proxies.'
L '- **Playback** (`bench_playback`, `bench_playback_with_scopes`, `bench_playback_multicam_grid` in `src/engine/worker.rs`). The video worker plays the project at the default preview, Preview (Auto) at 960x540, against a 29.97 fps clock that starts with the first frame, as the audio clock drives it in the app. Like the Video Preview, the test takes a frame once its number is due, polling every 1 ms, for 240 frames.'
L '  - *fps*: frames shown per second of wall time.'
L '  - *Dropped*: frames never shown (the worker skipped them to catch up, or a newer one was already due), as a share of the frames due.'
L '  - *Late layer frames*: layer pictures that missed their 25 ms deadline (the layer held its last picture) or that a decoder read past.'
L '  - *Play start*: from Play to the first frame, decoders cold (each run starts a new worker).'
L '  - *Video behind audio*: for each frame shown, the clock time when it went on screen less its own time: the preview pipeline''s A/V offset, before the display and the audio device latency (which the player compensates, R9).'
L '  - *Unpaced*: frames composed per second when nothing paces the worker (each frame waits for its decoders).'
L '- **Scopes**: the same playback while a thread analyses a 960x540 frame with all four Video Scopes 10 times a second (Update Scopes while Playing).'
L '- **Multicam grid**: the four clips made one multicamera track; the Video Preview shows the 2x2 take grid.'
L '- **Scrub** (`bench_scrub`): 40 paused frame requests on one layer at 960x540, as dragging the cursor makes them: 30 forward steps, then jumps (300, 100, 250, 20) and steps after them. A jump in GOP-250 media respawns its decoder.'
L '- **Adjust Size and Quality for Optimal Playback** (`bench_adaptive_quality` in `src/engine/mod.rs`): the four layers at Best (Full), 1920x1080, looped for 60 s through the Video Preview itself (`decode::Preview`, a 60 Hz UI loop against the wall clock), with the option off and then on.'
L ''

L '## Playback, Preview (960x540)'
L ''
L '| Layers | fps | Dropped | Late layer frames | Play start | Video behind audio p50 / p95 / max | Unpaced |'
L '|---|---|---|---|---|---|---|'
foreach ($r in Rows 'playback') { L "| $($r.layers) | $($r.fps) | $($r.drop_pct) % | $($r.late_layer_frames) | $($r.start_ms) ms | $($r.av_p50_ms) / $($r.av_p95_ms) / $($r.av_max_ms) ms | $($r.unpaced_fps) fps |" }
L ''
L '### With the Video Scopes updating while playing'
L ''
L '| Layers | fps | Dropped | Late layer frames | Play start | Video behind audio p50 / p95 |'
L '|---|---|---|---|---|---|'
foreach ($r in Rows 'scopes') { L "| $($r.layers) | $($r.fps) | $($r.drop_pct) % | $($r.late_layer_frames) | $($r.start_ms) ms | $($r.av_p50_ms) / $($r.av_p95_ms) ms |" }
L ''
L '### Multicamera take grid'
L ''
L '| Takes | fps | Dropped | Late layer frames | Play start | Video behind audio p50 / p95 |'
L '|---|---|---|---|---|---|'
foreach ($r in Rows 'multicam') { L "| $($r.takes) | $($r.fps) | $($r.drop_pct) % | $($r.late_layer_frames) | $($r.start_ms) ms | $($r.av_p50_ms) / $($r.av_p95_ms) ms |" }
L ''
L '## Scrub (one layer, original media, 960x540)'
L ''
$s = Rows 'scrub' | Select-Object -First 1
L '| p50 | p95 | max |'
L '|---|---|---|'
L "| $($s.p50_ms) ms | $($s.p95_ms) ms | $($s.max_ms) ms |"
L ''
L '## Adjust Size and Quality for Optimal Playback (4 layers, Best (Full))'
L ''
L '| Option | Dropped over 60 s | Dropped over the last 10 s | Setting changes | Setting at the end |'
L '|---|---|---|---|---|'
foreach ($r in Rows 'adaptive') { L "| $($r.adjust) | $($r.drop_pct) % | $($r.last10_drop_pct) % | $($r.changes) | $($r.final) |" }
L ''
L 'With the option on, the preview steps down one rung (Full, Half, Quarter, then Draft) when more than 2 % of the frames in 2 s drop, and back up after 10 s without a drop; a step up that drops again doubles the wait before the next try (up to 160 s). Every change restarts the decoders at the new size, and on GOP-250 media that costs a stall of about 1-3 s, which the totals above include. The render never uses these settings.'
L ''
L '## Gates (`docs/FEATURE_PLAN.md` 1.9)'
L ''
$four = Rows 'playback' | Where-Object { $_.layers -eq '4' } | Select-Object -First 1
$starts = (Rows 'playback' | ForEach-Object { [double]$_.start_ms } | Measure-Object -Maximum).Maximum
L '| Gate | Measured | Result |'
L '|---|---|---|'
L "| 4 x 1080p H.264 at 29.97 fps, under 1 % dropped | $($four.drop_pct) % at $($four.fps) fps | $(Gate ([double]$four.drop_pct -lt 1)) |"
L "| Play start at most 250 ms | at most $starts ms (1-4 layers) | $(Gate ($starts -le 250)) |"
L "| Scrub p95 under 150 ms on proxies | $($s.p95_ms) ms on original GOP-250 media, no proxies | not measured on proxies (R20) |"
[IO.File]::WriteAllText($Out, $md.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $Out"
