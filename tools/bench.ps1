    $c = Rows 'compose' | Where-Object { $_.kind -eq $kind[0] -and $_.compositor -eq 'cpu' } | Select-Object -First 1
    $g = Rows 'compose' | Where-Object { $_.kind -eq $kind[0] -and $_.compositor -eq 'gpu' } | Select-Object -First 1
