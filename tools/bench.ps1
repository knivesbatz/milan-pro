    $cells = foreach ($c in @('h264', 'hevc', 'av1')) {
        $e = Rows 'hwencode' | Where-Object { $_.encoder -eq "$($c)_$($dev[0])" } | Select-Object -First 1
        if (-not $e) { 'not built in' } elseif ($e.ok -eq 'true') { "$($e.ms) ms" } else { 'failed' }
    }
    L "| $($dev[1]) | $($cells -join ' | ') |"
